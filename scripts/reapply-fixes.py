    assert 'measure' in fixes
    for stage in range(4):
        replace('src/frame.c',f'    zy_stage_begin({stage}, image);',
                f'    zy_meter_stage_begin({stage});\n    zy_stage_begin({stage}, image);')
        replace('src/frame.c',f'    zy_stage_end({stage});',
                f'    zy_stage_end({stage});\n    zy_meter_stage_end({stage});')
    # The real target ships the assembly resolve stage. Hooks surround the
